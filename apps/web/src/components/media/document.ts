export type RetargetStrategy = "contain" | "cover";
export type RetargetAnchor = "center" | "top" | "bottom" | "start" | "end";

export interface RetargetOptions {
  /** `contain` fits everything inside (adds margin); `cover` fills and may crop. */
  strategy?: RetargetStrategy;
  anchor?: RetargetAnchor;
  /** Keep the content's own aspect regardless of strategy (never stretches). */
  preserveAspect?: boolean;
  /**
   * Scale every text layer's typography with the applied uniform scale.
   *
   * A reframe is authoring-time reflow (docs/07), so a uniformly scaled box must
   * carry type at a matching size: if the boxes shrink while the type keeps its
   * authored absolute size, the copy overflows or truncates inside a box that no
   * longer describes it and the `shrink`/`wrap` fit policy is silently defeated.
   * Scaling `size`, `minSize`, `maxSize` and `letterSpacing` together keeps the
   * result legible and the fit policy meaningful.
   *
   * Set `false` only when the consumer re-flows type itself — for example through
   * the per-layer `reflow` callback or an external layout pass — and therefore
   * owns the resulting sizes.
   *
   * @default true
   */
  scaleText?: boolean;
  /** Per-layer override, in new-artboard design px. The authoring escape hatch. */
  reflow?: (layer: Layer, nextTransform: LayerTransform) => LayerTransform;
}

export interface RetargetResult {
  document: MediaDocument;
  scale: number;
  offset: { x: number; y: number };
  diagnostics: Diagnostic[];
}

function anchorOffset(
  anchor: RetargetAnchor,
  scaled: Size,
  frame: Size
): { x: number; y: number } {
  const slackX = frame.width - scaled.width;
  const slackY = frame.height - scaled.height;
  switch (anchor) {
    case "top":
      return { x: slackX / 2, y: 0 };
    case "bottom":
      return { x: slackX / 2, y: slackY };
    case "start":
      return { x: 0, y: slackY / 2 };
    case "end":
      return { x: slackX, y: slackY / 2 };
    case "center":
    default:
      return { x: slackX / 2, y: slackY / 2 };
  }
}

/**
 * Reframes a document onto a different artboard at **authoring time**.
 *
 * Layers are scaled uniformly — a landscape composition is never stretched into
 * a portrait one. `contain` fits the whole design inside the target (small
 * margins may appear); `cover` fills the target and lets the reference bounds
 * crop. An optional `reflow` callback lets an author reposition individual
 * layers, which is how a genuinely different vertical layout is produced rather
 * than a scaled copy.
 *
 * Typography travels with the geometry. With `scaleText` (default `true`) every
 * text layer's `size`, `minSize`, `maxSize` and `letterSpacing` are multiplied
 * by the same uniform scale as its box, so a reframed composition stays legible
 * and its `shrink`/`wrap` policy keeps resolving against a box that matches its
 * type. This is authoring-time reflow, not output scaling: docs/11 requires that
 * *output scaling must not alter layout decisions*, whereas a reframe here
 * deliberately re-authors the layout at the target size. Each text layer is
 * scaled exactly once, whether or not it is nested in a group. Pass
 * `scaleText: false` to keep the authored sizes untouched when the consumer
 * re-flows type itself (for example via the `reflow` callback).
 */
export function retargetArtboard(
  document: MediaDocument,
  target: ArtboardInput,
  options: RetargetOptions = {}
): RetargetResult {
  const { strategy = "contain", anchor = "center", preserveAspect = true, scaleText = true, reflow } = options;
  const nextArtboard = createArtboard({
    ...target,
    background: target.background ?? document.artboard.background,
    safeRegion: target.safeRegion ?? DEFAULT_SAFE_INSET_RATIO,
  });

  const source: Size = { width: document.artboard.width, height: document.artboard.height };
  const frame: Size = { width: nextArtboard.width, height: nextArtboard.height };

  const scaleX = frame.width / source.width;
  const scaleY = frame.height / source.height;
  const scale = preserveAspect
    ? strategy === "cover"
      ? Math.max(scaleX, scaleY)
      : Math.min(scaleX, scaleY)
    : Math.min(scaleX, scaleY);

  const scaled: Size = { width: source.width * scale, height: source.height * scale };
  const offset = anchorOffset(anchor, scaled, frame);

  const mapTransform = (transform: LayerTransform): LayerTransform => {
    const mapped: LayerTransform = {
      x: round(transform.x * scale + offset.x),
      y: round(transform.y * scale + offset.y),
      width: round(transform.width * scale),
      height: round(transform.height * scale),
    };
    if (transform.rotation) mapped.rotation = transform.rotation;
    if (transform.anchorX !== undefined) mapped.anchorX = transform.anchorX;
    if (transform.anchorY !== undefined) mapped.anchorY = transform.anchorY;
    return mapped;
  };

  /**
   * Scale a text spec by the uniform factor. `round()` is monotonic, so a valid
   * authored `minSize <= size <= maxSize` survives scaling; the clamp only
   * guards a degenerate range and never emits an inverted one.
   */
  const mapTextSpec = (spec: TextSpec): TextSpec => {
    const size = round(spec.size * scale);
    const mapped: TextSpec = {
      ...spec,
      size,
      letterSpacing: round(spec.letterSpacing * scale),
    };
    if (spec.minSize !== undefined) mapped.minSize = Math.min(round(spec.minSize * scale), size);
    if (spec.maxSize !== undefined) mapped.maxSize = Math.max(round(spec.maxSize * scale), size);
    return mapped;
  };

  const layers = document.layers.map((layer) => {
    const mapped = mapTransform(layer.transform);
    const transform = reflow ? reflow(layer, mapped) : mapped;
    if (scaleText && isTextLayer(layer)) {
      // Scaled from the authored spec exactly once: an ancestor group scales its
      // own transform, never its children's typography.
      return { ...layer, transform, text: mapTextSpec(layer.text) };
    }
    return { ...layer, transform } as Layer;
  });

  const guides = document.guides.map((guide) =>
    guide.axis === "x"
      ? { ...guide, position: round(guide.position * scale + offset.x) }
      : { ...guide, position: round(guide.position * scale + offset.y) }
  );

  const next: MediaDocument = normalizeDocument({
    ...document,
    id: document.id,
    artboard: nextArtboard,
    layers,
    guides,
    metadata: {
      ...document.metadata,
      aspectVariant: nextArtboard.aspect,
    },
  });

  const diagnostics = validateDocument(next);
  if (strategy === "cover") {
    const outOfFrame = overflowLayers(next.layers, {
      x: 0,
      y: 0,
      width: nextArtboard.width,
      height: nextArtboard.height,
    });
    for (const overflow of outOfFrame) {
      diagnostics.push({
        code: "retarget-crop",
        severity: "warning",
        sceneId: next.id,
        layerId: overflow.layerId,
        message: `Layer is cropped after cover-retarget (${overflow.area} px outside the frame). Move it with retargetArtboard's reflow callback if that was not intended.`,
        path: "layers",
      });
    }
  }

  return { document: next, scale: round(scale, 6), offset: { x: round(offset.x), y: round(offset.y) }, diagnostics };
}

