export function presetForDimensions(width: number, height: number): AspectPreset {
  if (!Number.isFinite(width) || !Number.isFinite(height) || width <= 0 || height <= 0) return "custom";
  const ratio = width / height;
  const entries = Object.entries(ASPECT_PRESETS) as Array<
    [Exclude<AspectPreset, "custom">, AspectPresetDefinition]
  >;
  for (const [name, definition] of entries) {
    if (Math.abs(ratio - definition.ratio) <= 0.002) return name;
  }
  return "custom";
}

export function sizeForPreset(preset: Exclude<AspectPreset, "custom">): Size {
  const { width, height } = ASPECT_PRESETS[preset];
  return { width, height };
}

export interface ArtboardInput {
  id?: string;
  width?: number;
  height?: number;
  preset?: Exclude<AspectPreset, "custom">;
  background?: string;
  safeRegion?: Insets | number;
  bleed?: Insets | number;
  crop?: Insets | number;
}

export function createArtboard(input: ArtboardInput = {}): ArtboardSpec {
  const preset = input.preset;
  const presetSize = preset ? sizeForPreset(preset) : undefined;
  const width = input.width ?? presetSize?.width ?? 1280;
  const height = input.height ?? presetSize?.height ?? 720;
  const size: Size = { width, height };

  const asInsets = (value: Insets | number | undefined, fill: Insets): Insets => {
    if (value === undefined) return fill;
    if (typeof value === "number") return insetsFromRatio(value, size);
    return { ...value };
  };

  return {
    id: input.id ?? "artboard",
    width,
    height,
    aspect: preset ?? presetForDimensions(width, height),
    background: input.background ?? "var(--km-surface-canvas)",
    safeRegion: asInsets(input.safeRegion, defaultSafeRegion(size)),
    bleed: asInsets(input.bleed, zeroInsets()),
    crop: asInsets(input.crop, zeroInsets()),
  };
}

export interface DocumentInput {
  id?: string;
  artboard?: ArtboardSpec | ArtboardInput;
  fonts?: Record<string, FontAsset>;
  assets?: Record<string, ImageAsset>;
  layers?: Layer[];
  guides?: Guide[];
  grid?: GridSpec;
  metadata?: MediaMetadata;
}

export function createDocument(input: DocumentInput = {}): MediaDocument {
  const artboardInput = input.artboard ?? {};
  const artboard =
    "aspect" in artboardInput && "safeRegion" in artboardInput
      ? (artboardInput as ArtboardSpec)
      : createArtboard(artboardInput as ArtboardInput);

  return {
    schemaVersion: MEDIA_SCHEMA_VERSION,
    id: input.id ?? "composition",
    artboard,
    fonts: input.fonts ?? {},
    assets: input.assets ?? {},
    layers: input.layers ?? [],
    guides: input.guides ?? [],
    ...(input.grid ? { grid: input.grid } : {}),
    ...(input.metadata ? { metadata: input.metadata } : {}),
  };
}

/** Fills defaults and rounds geometry so two structurally-equal documents serialize identically. */
export function normalizeDocument(document: MediaDocument): MediaDocument {
  const layers = resolveLayerOrder(document.layers).map((layer) => {
    const transform: LayerTransform = {
      x: round(layer.transform.x),
      y: round(layer.transform.y),
      width: round(layer.transform.width),
      height: round(layer.transform.height),
    };
    if (layer.transform.rotation) transform.rotation = round(layer.transform.rotation);
    if (layer.transform.anchorX !== undefined) transform.anchorX = layer.transform.anchorX;
    if (layer.transform.anchorY !== undefined) transform.anchorY = layer.transform.anchorY;
    const base = { ...layer, transform };
    if (base.kind === "text") {
      return {
        ...base,
        text: { ...base.text, spans: base.text.spans.map((span) => ({ ...span })) },
      } as TextLayer;
    }
    return base;
  });

  return {
    ...document,
    artboard: { ...document.artboard, safeRegion: { ...document.artboard.safeRegion } },
    fonts: Object.fromEntries(
      Object.entries(document.fonts).sort(([a], [b]) => (a < b ? -1 : 1))
    ),
    assets: Object.fromEntries(
      Object.entries(document.assets).sort(([a], [b]) => (a < b ? -1 : 1))
    ),
    layers,
    guides: [...document.guides].sort((a, b) => (a.axis === b.axis ? a.position - b.position : a.axis < b.axis ? -1 : 1)),
  };
}

