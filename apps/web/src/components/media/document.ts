/**
 * JSON with object keys sorted and numbers rounded, so structurally equal
 * documents hash and diff identically across runs and machines.
 */
export function stableStringify(value: unknown, precision = 3): string {
  const seen = new WeakSet<object>();
  const normalize = (input: unknown): unknown => {
    if (typeof input === "number") return round(input, precision);
    if (Array.isArray(input)) return input.map(normalize);
    if (input && typeof input === "object") {
      const object = input as Record<string, unknown>;
      if (seen.has(object)) throw new Error("Cannot serialize a cyclic document.");
      seen.add(object);
      const sorted: Record<string, unknown> = {};
      for (const key of Object.keys(object).sort()) {
        const entry = object[key];
        if (entry === undefined) continue;
        sorted[key] = normalize(entry);
      }
      seen.delete(object);
      return sorted;
    }
    return input;
  };
  return JSON.stringify(normalize(value));
}

export function serializeDocument(document: MediaDocument, space = 2): string {
  const normalized = normalizeDocument(document);
  const stable = stableStringify(normalized);
  return space > 0 ? JSON.stringify(JSON.parse(stable), null, space) : stable;
}

/** FNV-1a 32-bit hash, hex encoded. Dependency-free content fingerprint for cache keys and manifests. */
export function documentHash(document: MediaDocument): string {
  const input = stableStringify(normalizeDocument(document));
  let hash = 0x811c9dc5;
  for (let index = 0; index < input.length; index += 1) {
    hash ^= input.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash.toString(16).padStart(8, "0");
}

export interface ParseResult {
  document: MediaDocument | null;
  diagnostics: Diagnostic[];
}

/**
 * Parses JSON into a document without throwing. Structural problems are
 * returned as diagnostics; warnings do not block, errors leave `document` null
 * because a partially-valid document must never be rendered as if complete.
 */
export function parseDocument(input: string | unknown): ParseResult {
  let value: unknown = input;
  if (typeof input === "string") {
    try {
      value = JSON.parse(input);
    } catch (error) {
      return {
        document: null,
        diagnostics: [
          {
            code: "document-parse-failed",
            severity: "error",
            message: error instanceof Error ? error.message : "Document JSON is not parseable.",
          },
        ],
      };
    }
  }

  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return {
      document: null,
      diagnostics: [
        { code: "document-shape-invalid", severity: "error", message: "Document must be a JSON object." },
      ],
    };
  }

  const candidate = value as Partial<MediaDocument>;
  const missing: string[] = [];
  for (const key of ["id", "artboard", "fonts", "assets", "layers", "guides"] as const) {
    if (candidate[key] === undefined) missing.push(key);
  }
  if (missing.length > 0) {
    return {
      document: null,
      diagnostics: [
        {
          code: "document-shape-invalid",
          severity: "error",
          message: `Document is missing required field(s): ${missing.join(", ")}.`,
        },
      ],
    };
  }

  const document = normalizeDocument(candidate as MediaDocument);
  const diagnostics = validateDocument(document);
  return { document: hasBlockingDiagnostics(diagnostics) ? null : document, diagnostics };
}

