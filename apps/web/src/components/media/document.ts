/** Round to a stable precision so serialized output is byte-identical across runs. */
export function round(value: number, precision = 3): number {
  if (!Number.isFinite(value)) return value;
  const factor = 10 ** precision;
  return Math.round(value * factor) / factor;
}

export function insetsFromRatio(ratio: number, size: Size): Insets {
  const shortest = Math.min(size.width, size.height);
  const value = round(shortest * ratio);
  return { top: value, right: value, bottom: value, left: value };
}

export function zeroInsets(): Insets {
  return { top: 0, right: 0, bottom: 0, left: 0 };
}

export function defaultSafeRegion(artboard: Pick<ArtboardSpec, "width" | "height">): Insets {
  return insetsFromRatio(DEFAULT_SAFE_INSET_RATIO, artboard);
}

/** Horizontal and vertical inset totals. */
export function insetsSize(insets: Insets): Size {
  return {
    width: insets.left + insets.right,
    height: insets.top + insets.bottom,
  };
}

export function rectFromBounds(x1: number, y1: number, x2: number, y2: number): Rect {
  return {
    x: Math.min(x1, x2),
    y: Math.min(y1, y2),
    width: Math.abs(x2 - x1),
    height: Math.abs(y2 - y1),
  };
}

export function rectRight(rect: Rect): number {
  return rect.x + rect.width;
}

export function rectBottom(rect: Rect): number {
  return rect.y + rect.height;
}

/** The axis-aligned bounding box of a rect rotated about its normalised anchor. */
export function rotatedBounds(
  rect: Rect,
  rotation: number | undefined,
  anchorX = 0,
  anchorY = 0
): Rect {
  if (!rotation) return { ...rect };
  const rad = (rotation * Math.PI) / 180;
  const cos = Math.cos(rad);
  const sin = Math.sin(rad);
  const ax = rect.x + rect.width * anchorX;
  const ay = rect.y + rect.height * anchorY;
  const corners: Array<[number, number]> = [
    [rect.x, rect.y],
    [rectRight(rect), rect.y],
    [rectRight(rect), rectBottom(rect)],
    [rect.x, rectBottom(rect)],
  ];
  const rotated = corners.map(([x, y]) => {
    const dx = x - ax;
    const dy = y - ay;
    return [ax + dx * cos - dy * sin, ay + dx * sin + dy * cos] as const;
  });
  const xs = rotated.map(([x]) => x);
  const ys = rotated.map(([, y]) => y);
  return rectFromBounds(Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys));
}

export function layerBounds(layer: Layer): Rect {
  return rotatedBounds(
    layer.transform,
    layer.transform.rotation,
    layer.transform.anchorX ?? 0,
    layer.transform.anchorY ?? 0
  );
}

export function unionBounds(rects: readonly Rect[]): Rect | null {
  if (rects.length === 0) return null;
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (const rect of rects) {
    minX = Math.min(minX, rect.x);
    minY = Math.min(minY, rect.y);
    maxX = Math.max(maxX, rectRight(rect));
    maxY = Math.max(maxY, rectBottom(rect));
  }
  return rectFromBounds(minX, minY, maxX, maxY);
}

export interface Overflow {
  layerId: string;
  /** Pixels beyond each edge of the reference rect (0 when inside). */
  beyond: Insets;
  /** Total overflow area in design px². */
  area: number;
}

/** Measures how far each layer's bounds stray outside `reference`. Used by the crop/overflow QA gate. */
export function overflowLayers(
  layers: readonly Layer[],
  reference: Rect,
  options: { ignoreInvisible?: boolean } = {}
): Overflow[] {
  const results: Overflow[] = [];
  for (const layer of layers) {
    if (options.ignoreInvisible && !layer.visible) continue;
    const bounds = layerBounds(layer);
    const beyond: Insets = {
      top: Math.max(0, round(reference.y - bounds.y)),
      right: Math.max(0, round(rectRight(bounds) - rectRight(reference))),
      bottom: Math.max(0, round(rectBottom(bounds) - rectBottom(reference))),
      left: Math.max(0, round(reference.x - bounds.x)),
    };
    const area = round(beyond.top + beyond.right + beyond.bottom + beyond.left);
    if (area > 0) results.push({ layerId: layer.id, beyond, area });
  }
  return results;
}

export function rectsIntersect(a: Rect, b: Rect): boolean {
  return (
    a.x < rectRight(b) && rectRight(a) > b.x && a.y < rectBottom(b) && rectBottom(a) > b.y
  );
}

export function intersectionArea(a: Rect, b: Rect): number {
  const width = Math.min(rectRight(a), rectRight(b)) - Math.max(a.x, b.x);
  const height = Math.min(rectBottom(a), rectBottom(b)) - Math.max(a.y, b.y);
  if (width <= 0 || height <= 0) return 0;
  return round(width * height);
}

