export function layerKindLabel(layer: Layer): string {
  switch (layer.kind) {
    case "text":
      return "Text";
    case "media":
      return "Media";
    case "shape":
      return "Shape";
    case "group":
      return "Group";
    default:
      return "Layer";
  }
}

/** Accessible name for a layer: its own summary, then media alt, then visible text, then name. */
export function layerAccessibleName(layer: Layer): string {
  if (layer.summary) return layer.summary;
  if (isMediaLayer(layer)) return layer.media.alt ?? layer.name;
  if (isTextLayer(layer)) return textSpecToString(layer.text) || layer.name;
  return layer.name;
}
