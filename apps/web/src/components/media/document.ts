const ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._:-]*$/;

function invalidId(id: unknown): boolean {
  return typeof id !== "string" || id.length === 0 || !ID_PATTERN.test(id);
}

function isFiniteNumber(value: unknown): value is number {
  return typeof value === "number" && Number.isFinite(value);
}

/** Walks the document and reports every non-finite number with a JSON-ish path. */
function findNonFinite(value: unknown, path: string, out: Array<{ path: string }>): void {
  if (typeof value === "number") {
    if (!Number.isFinite(value)) out.push({ path });
    return;
  }
  if (Array.isArray(value)) {
    value.forEach((entry, index) => findNonFinite(entry, `${path}[${index}]`, out));
    return;
  }
  if (value && typeof value === "object") {
    for (const [key, entry] of Object.entries(value)) {
      findNonFinite(entry, path ? `${path}.${key}` : key, out);
    }
  }
}

function detectCycles(layers: readonly Layer[]): string[] {
  const byId = new Map(layers.map((layer) => [layer.id, layer]));
  const state = new Map<string, "visiting" | "done">();
  const cycles = new Set<string>();

  const visit = (id: string): void => {
    const current = state.get(id);
    if (current === "done") return;
    if (current === "visiting") {
      cycles.add(id);
      return;
    }
    state.set(id, "visiting");
    const layer = byId.get(id);
    const parentId = layer ? normalizeParentId(layer) : null;
    if (parentId && byId.has(parentId)) visit(parentId);
    state.set(id, "done");
  };

  for (const layer of layers) visit(layer.id);
  return [...cycles];
}

/**
 * Validates a document against the R0 rules in docs/11 §8: unknown ids, parent
 * cycles, non-finite numbers, unsupported schema versions and dangling asset or
 * font references are rejected as errors. Layout risks (overflow, opacity out
 * of range, empty groups) are warnings so a preview can still be inspected.
 */
export function validateDocument(document: MediaDocument): Diagnostic[] {
  const diagnostics: Diagnostic[] = [];
  const sceneId = typeof document.id === "string" ? document.id : undefined;
  type PushDiagnostic = Omit<Diagnostic, "sceneId"> & { sceneId?: string };
  const push = (diagnostic: PushDiagnostic): void => {
    diagnostics.push({ ...diagnostic, sceneId: diagnostic.sceneId ?? sceneId });
  };

  if (document.schemaVersion !== MEDIA_SCHEMA_VERSION) {
    push({
      code: "schema-version-unsupported",
      severity: "error",
      message: `Unsupported schemaVersion ${String(document.schemaVersion)}; this build reads ${MEDIA_SCHEMA_VERSION}.`,
      path: "schemaVersion",
    });
  }

  if (invalidId(document.id)) {
    push({ code: "id-invalid", severity: "error", message: "Document id must be a non-empty slug.", path: "id" });
  }

  const nonFinite: Array<{ path: string }> = [];
  findNonFinite(document, "", nonFinite);
  for (const entry of nonFinite) {
    push({
      code: "number-not-finite",
      severity: "error",
      message: "NaN/Infinity is not representable in the document; fix the authored value.",
      path: entry.path,
    });
  }

  const { artboard } = document;
  if (!isFiniteNumber(artboard.width) || artboard.width <= 0 || !isFiniteNumber(artboard.height) || artboard.height <= 0) {
    push({
      code: "artboard-invalid-size",
      severity: "error",
      message: `Artboard must have positive finite width/height (got ${artboard.width}×${artboard.height}).`,
      path: "artboard",
    });
  }
  for (const [key, insets] of [
    ["safeRegion", artboard.safeRegion],
    ["bleed", artboard.bleed],
    ["crop", artboard.crop],
  ] as const) {
    for (const edge of ["top", "right", "bottom", "left"] as const) {
      if (!isFiniteNumber(insets[edge]) || insets[edge] < 0) {
        push({
          code: "artboard-inset-invalid",
          severity: "error",
          message: `artboard.${key}.${edge} must be a non-negative finite number.`,
          path: `artboard.${key}.${edge}`,
        });
      }
    }
  }

  const layerIds = new Set<string>();
  for (const [index, layer] of document.layers.entries()) {
    const path = `layers[${index}]`;
    if (invalidId(layer.id)) {
      push({
        code: "id-invalid",
        severity: "error",
        message: `Layer id "${String(layer.id)}" must be a non-empty slug.`,
        layerId: typeof layer.id === "string" ? layer.id : undefined,
        path: `${path}.id`,
      });
    } else if (layerIds.has(layer.id)) {
      push({
        code: "layer-id-duplicate",
        severity: "error",
        message: `Duplicate layer id "${layer.id}"; ids must be unique and stable.`,
        layerId: layer.id,
        path: `${path}.id`,
      });
    } else {
      layerIds.add(layer.id);
    }

    if (!LAYER_KINDS.includes(layer.kind)) {
      push({
        code: "enum-invalid",
        severity: "error",
        message: `Unknown layer kind "${String(layer.kind)}".`,
        layerId: layer.id,
        path: `${path}.kind`,
      });
    }
    if (!BLEND_MODES.includes(layer.blend)) {
      push({
        code: "enum-invalid",
        severity: "error",
        message: `Unknown blend mode "${String(layer.blend)}".`,
        layerId: layer.id,
        path: `${path}.blend`,
      });
    }
    if (!isFiniteNumber(layer.opacity) || layer.opacity < 0 || layer.opacity > 1) {
      push({
        code: "opacity-out-of-range",
        severity: "error",
        message: `Layer opacity must be within 0..1 (got ${String(layer.opacity)}).`,
        layerId: layer.id,
        path: `${path}.opacity`,
      });
    }
    const shadow = layer.appearance?.dropShadow;
    if (shadow) {
      const validNumbers = [shadow.dx, shadow.dy, shadow.blur, shadow.opacity].every(isFiniteNumber);
      if (!validNumbers || shadow.blur < 0 || shadow.blur > 128 || shadow.opacity < 0 || shadow.opacity > 1 ||
        typeof shadow.color !== "string" || !/^#[\da-f]{6}$/i.test(shadow.color)) {
        push({
          code: "layer-appearance-invalid",
          severity: "error",
          message: "Drop shadow needs finite offsets, 0–128px blur, hex color and 0–1 opacity.",
          layerId: layer.id,
          path: `${path}.appearance.dropShadow`,
        });
      }
    }
    if (!isFiniteNumber(layer.z)) {
      push({
        code: "number-not-finite",
        severity: "error",
        message: "Layer z must be a finite number.",
        layerId: layer.id,
        path: `${path}.z`,
      });
    }
    if (layer.parentId != null && !layerIds.has(layer.parentId) && !document.layers.some((entry) => entry.id === layer.parentId)) {
      push({
        code: "layer-parent-missing",
        severity: "error",
        message: `Layer "${layer.id}" references missing parent "${layer.parentId}".`,
        layerId: layer.id,
        path: `${path}.parentId`,
      });
    }

    if (layer.kind === "text") {
      const spec = layer.text;
      if (!spec.spans || !Array.isArray(spec.spans)) {
        push({
          code: "text-spans-missing",
          severity: "error",
          message: "Text layer must declare a spans array.",
          layerId: layer.id,
          path: `${path}.text.spans`,
        });
      } else {
        if (!document.fonts[spec.fontId]) {
          push({
            code: "text-font-missing",
            severity: "error",
            message: `Text layer references font "${spec.fontId}" which is not declared in document.fonts.`,
            layerId: layer.id,
            path: `${path}.text.fontId`,
          });
        }
        for (const [spanIndex, span] of spec.spans.entries()) {
          const spanFont = span.fontId;
          if (spanFont && !document.fonts[spanFont]) {
            push({
              code: "text-font-missing",
              severity: "error",
              message: `Span ${spanIndex} references font "${spanFont}" which is not declared in document.fonts.`,
              layerId: layer.id,
              path: `${path}.text.spans[${spanIndex}].fontId`,
            });
          }
        }
      }
      if (!TEXT_FITS.includes(spec.fit)) {
        push({ code: "enum-invalid", severity: "error", message: `Unknown text fit "${String(spec.fit)}".`, layerId: layer.id, path: `${path}.text.fit` });
      }
      if (!TEXT_ALIGNS.includes(spec.align)) {
        push({ code: "enum-invalid", severity: "error", message: `Unknown text align "${String(spec.align)}".`, layerId: layer.id, path: `${path}.text.align` });
      }
      if (!TEXT_DIRECTIONS.includes(spec.direction)) {
        push({ code: "enum-invalid", severity: "error", message: `Unknown text direction "${String(spec.direction)}".`, layerId: layer.id, path: `${path}.text.direction` });
      }
      if (!TEXT_ELEMENTS.includes(spec.as)) {
        push({ code: "enum-invalid", severity: "error", message: `Unknown text element "${String(spec.as)}".`, layerId: layer.id, path: `${path}.text.as` });
      }
      if (!isFiniteNumber(spec.size) || spec.size <= 0) {
        push({ code: "text-size-invalid", severity: "error", message: "Text size must be a positive number.", layerId: layer.id, path: `${path}.text.size` });
      }
      if (spec.fit === "shrink") {
        const min = spec.minSize ?? 0;
        const max = spec.maxSize ?? spec.size;
        if (min > 0 && max > 0 && min > max) {
          push({
            code: "text-shrink-range-invalid",
            severity: "error",
            message: `minSize (${min}) cannot exceed maxSize (${max}).`,
            layerId: layer.id,
            path: `${path}.text.minSize`,
          });
        }
      }
      if (!layer.summary) {
        push({
          code: "text-summary-missing",
          severity: "warning",
          message: "Text layer has no semantic summary; assistive technology will read the visible text only.",
          layerId: layer.id,
          path: `${path}.summary`,
        });
      }
    }

    if (layer.kind === "media") {
      if (!document.assets[layer.media.assetId]) {
        push({
          code: "media-asset-missing",
          severity: "error",
          message: `Media layer references asset "${layer.media.assetId}" which is not declared in document.assets.`,
          layerId: layer.id,
          path: `${path}.media.assetId`,
        });
      }
      if (!MEDIA_FITS.includes(layer.media.fit)) {
        push({ code: "enum-invalid", severity: "error", message: `Unknown media fit "${String(layer.media.fit)}".`, layerId: layer.id, path: `${path}.media.fit` });
      }
      if (!MEDIA_MASK_KINDS.includes(layer.media.mask?.kind)) {
        push({ code: "enum-invalid", severity: "error", message: `Unknown media mask "${String(layer.media.mask?.kind)}".`, layerId: layer.id, path: `${path}.media.mask.kind` });
      }
      const focal = layer.media.focalPoint;
      if (!isFiniteNumber(focal?.x) || !isFiniteNumber(focal?.y) || focal.x < 0 || focal.x > 1 || focal.y < 0 || focal.y > 1) {
        push({
          code: "media-focal-invalid",
          severity: "error",
          message: "Focal point must be normalised within 0..1 on both axes.",
          layerId: layer.id,
          path: `${path}.media.focalPoint`,
        });
      }
      if (!layer.media.alt && !layer.summary && !layer.media.decorative) {
        push({
          code: "media-alt-missing",
          severity: "warning",
          message: "Non-decorative media has no alt text; set media.alt, layer.summary or mark it decorative.",
          layerId: layer.id,
          path: `${path}.media.alt`,
        });
      }
    }

    if (layer.kind === "shape" && !SHAPE_KINDS.includes(layer.shape?.kind)) {
      push({ code: "enum-invalid", severity: "error", message: `Unknown shape kind "${String(layer.shape?.kind)}".`, layerId: layer.id, path: `${path}.shape.kind` });
    }

    if (layer.kind === "group" && childrenOf(document.layers, layer.id).length === 0) {
      push({
        code: "group-empty",
        severity: "warning",
        message: `Group "${layer.id}" has no children.`,
        layerId: layer.id,
        path,
      });
    }

    if (layer.transform.width < MIN_LAYER_SIZE || layer.transform.height < MIN_LAYER_SIZE) {
      push({
        code: "layer-size-invalid",
        severity: "error",
        message: "Layer width/height must not be negative.",
        layerId: layer.id,
        path: `${path}.transform`,
      });
    }
  }

  if (document.layers.length > MAX_LAYER_COUNT) {
    push({
      code: "layer-count-exceeded",
      severity: "error",
      message: `Document holds ${document.layers.length} layers; the supported maximum is ${MAX_LAYER_COUNT}.`,
      path: "layers",
    });
  }

  for (const cycleId of detectCycles(document.layers)) {
    push({
      code: "layer-parent-cycle",
      severity: "error",
      message: `Layer "${cycleId}" is part of a parent/child cycle.`,
      layerId: cycleId,
      path: "layers",
    });
  }

  const guideIds = new Set<string>();
  for (const [index, guide] of document.guides.entries()) {
    if (guideIds.has(guide.id)) {
      push({ code: "guide-id-duplicate", severity: "error", message: `Duplicate guide id "${guide.id}".`, path: `guides[${index}].id` });
    }
    guideIds.add(guide.id);
    if (guide.axis !== "x" && guide.axis !== "y") {
      push({ code: "enum-invalid", severity: "error", message: `Guide axis must be "x" or "y".`, path: `guides[${index}].axis` });
    }
  }

  const reference: Rect = { x: 0, y: 0, width: artboard.width, height: artboard.height };
  if (Number.isFinite(reference.width) && Number.isFinite(reference.height)) {
    for (const overflow of overflowLayers(document.layers, reference)) {
      push({
        code: "layer-overflow",
        severity: "warning",
        message: `Layer extends beyond the artboard (top ${overflow.beyond.top}, right ${overflow.beyond.right}, bottom ${overflow.beyond.bottom}, left ${overflow.beyond.left} px).`,
        layerId: overflow.layerId,
        path: "layers",
      });
    }
  }

  return diagnostics;
}

export function countBySeverity(diagnostics: readonly Diagnostic[]): { errors: number; warnings: number } {
  let errors = 0;
  let warnings = 0;
  for (const diagnostic of diagnostics) {
    if (diagnostic.severity === "error") errors += 1;
    else warnings += 1;
  }
  return { errors, warnings };
}

export function hasBlockingDiagnostics(diagnostics: readonly Diagnostic[]): boolean {
  return diagnostics.some((diagnostic) => diagnostic.severity === "error");
}

