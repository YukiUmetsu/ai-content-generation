/**
 * Candidate lines a moving rectangle can snap to. Artboard edges/centres and
 * other layers' edges/centres are always candidates; static guides are included
 * by the caller passing them in. Locked and invisible layers are skipped.
 */
export function snapTargets(
  layers: readonly Layer[],
  artboard: Pick<ArtboardSpec, "width" | "height">,
  guides: readonly Guide[] = [],
  options: SnapOptions = {}
): SnapTarget[] {
  const {
    excludeIds = [],
    includeArtboardEdges = true,
    includeLayerEdges = true,
    includeCenters = true,
    includeGrid = false,
    gridSize = 0,
  } = options;
  const excluded = new Set(excludeIds);
  const targets: SnapTarget[] = [];

  if (includeArtboardEdges) {
    targets.push(
      { axis: "x", position: 0, kind: "artboard-edge" },
      { axis: "x", position: artboard.width, kind: "artboard-edge" },
      { axis: "y", position: 0, kind: "artboard-edge" },
      { axis: "y", position: artboard.height, kind: "artboard-edge" }
    );
  }
  if (includeCenters) {
    targets.push(
      { axis: "x", position: round(artboard.width / 2), kind: "artboard-center" },
      { axis: "y", position: round(artboard.height / 2), kind: "artboard-center" }
    );
  }
  for (const guide of guides) {
    targets.push({ axis: guide.axis, position: guide.position, kind: "guide", guideId: guide.id });
  }
  if (includeLayerEdges) {
    for (const layer of layers) {
      if (excluded.has(layer.id) || !layer.visible) continue;
      const bounds = layerBounds(layer);
      targets.push(
        { axis: "x", position: round(bounds.x), kind: "layer-edge", layerId: layer.id },
        { axis: "x", position: round(rectRight(bounds)), kind: "layer-edge", layerId: layer.id },
        { axis: "y", position: round(bounds.y), kind: "layer-edge", layerId: layer.id },
        { axis: "y", position: round(rectBottom(bounds)), kind: "layer-edge", layerId: layer.id }
      );
      if (includeCenters) {
        targets.push(
          {
            axis: "x",
            position: round(bounds.x + bounds.width / 2),
            kind: "layer-center",
            layerId: layer.id,
          },
          {
            axis: "y",
            position: round(bounds.y + bounds.height / 2),
            kind: "layer-center",
            layerId: layer.id,
          }
        );
      }
    }
  }
  if (includeGrid && gridSize > 0) {
    for (let x = gridSize; x < artboard.width; x += gridSize) {
      targets.push({ axis: "x", position: round(x), kind: "grid" });
    }
    for (let y = gridSize; y < artboard.height; y += gridSize) {
      targets.push({ axis: "y", position: round(y), kind: "grid" });
    }
  }
  return targets;
}

/**
 * Snaps the moving rect so its leading edge, trailing edge or centre aligns to
 * the nearest candidate line within `threshold`. Edges win over centres and the
 * axis with the smallest correction wins, so the result is stable regardless of
 * target enumeration order.
 */
export function applySnap(
  moving: Rect,
  targets: readonly SnapTarget[],
  options: SnapOptions = {}
): SnapResult {
  const { threshold = 6 } = options;
  const rect = { ...moving };
  const hits: SnapHit[] = [];

  for (const axis of ["x", "y"] as const) {
    const origin = axis === "x" ? rect.x : rect.y;
    const size = axis === "x" ? rect.width : rect.height;
    const candidates = targets.filter((target) => target.axis === axis);

    const edged = (["edge-min", "edge-max"] as const)
      .flatMap((role) =>
        candidates.map((target) => ({
          target,
          offset: role === "edge-min" ? target.position - origin : target.position - (origin + size),
          kind: role,
        }))
      )
      .filter((candidate) => Math.abs(candidate.offset) <= threshold)
      .sort((a, b) => Math.abs(a.offset) - Math.abs(b.offset));

    const centred = candidates
      .map((target) => ({ target, offset: target.position - (origin + size / 2) }))
      .filter((candidate) => Math.abs(candidate.offset) <= threshold)
      .sort((a, b) => Math.abs(a.offset) - Math.abs(b.offset));

    const best =
      edged.length > 0 && (centred.length === 0 || Math.abs(edged[0].offset) <= Math.abs(centred[0].offset))
        ? edged[0]
        : centred[0];

    if (!best) continue;
    const delta = round(best.offset);
    if (axis === "x") rect.x = round(rect.x + delta);
    else rect.y = round(rect.y + delta);
    hits.push({ axis, position: best.target.position, delta, target: best.target });
  }

  return { rect, hits };
}

