export function layerById(layers: readonly Layer[], id: string): Layer | undefined {
  return layers.find((layer) => layer.id === id);
}

export function childrenOf(layers: readonly Layer[], parentId: string | null): Layer[] {
  return layers.filter((layer) => (layer.parentId ?? null) === parentId);
}

/** Deterministic paint order: `z` ascending, ties broken by id so order never depends on input sequence. */
export function compareLayerOrder(a: Layer, b: Layer): number {
  if (a.z !== b.z) return a.z - b.z;
  return a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
}

export function resolveLayerOrder(layers: readonly Layer[]): Layer[] {
  return [...layers].sort(compareLayerOrder);
}

export interface LayerTreeNode {
  layer: Layer;
  children: LayerTreeNode[];
  depth: number;
  /** Paint order index among layers sharing a parent, lowest first. */
  order: number;
}

function normalizeParentId(layer: Layer): string | null {
  return layer.parentId ?? null;
}

/** Ordered forest for the layer panel: roots first, children depth-first in paint order. */
export function buildLayerTree(layers: readonly Layer[]): LayerTreeNode[] {
  const byParent = new Map<string | null, Layer[]>();
  for (const layer of layers) {
    const parent = normalizeParentId(layer);
    const bucket = byParent.get(parent);
    if (bucket) bucket.push(layer);
    else byParent.set(parent, [layer]);
  }
  for (const bucket of byParent.values()) bucket.sort(compareLayerOrder);

  const build = (parentId: string | null, depth: number, seen: Set<string>): LayerTreeNode[] => {
    const children = byParent.get(parentId) ?? [];
    return children
      .filter((layer) => !seen.has(layer.id))
      .map((layer, index) => {
        seen.add(layer.id);
        return {
          layer,
          depth,
          order: index,
          children: build(layer.id, depth + 1, seen),
        };
      });
  };

  return build(null, 0, new Set());
}

/** Ancestor chain from the layer's parent up to the root. */
export function ancestorsOf(layers: readonly Layer[], id: string): Layer[] {
  const index = new Map(layers.map((layer) => [layer.id, layer]));
  const chain: Layer[] = [];
  const seen = new Set<string>([id]);
  let current = index.get(id);
  while (current) {
    const parentId = normalizeParentId(current);
    if (!parentId) break;
    if (seen.has(parentId)) break;
    seen.add(parentId);
    const parent = index.get(parentId);
    if (!parent) break;
    chain.push(parent);
    current = parent;
  }
  return chain;
}

/** True when `layer` (or an ancestor) is hidden or locked. */
export function isLayerEffectivelyHidden(layers: readonly Layer[], layer: Layer): boolean {
  if (!layer.visible) return true;
  return ancestorsOf(layers, layer.id).some((ancestor) => !ancestor.visible);
}

export function isLayerEffectivelyLocked(layers: readonly Layer[], layer: Layer): boolean {
  if (layer.locked) return true;
  return ancestorsOf(layers, layer.id).some((ancestor) => ancestor.locked);
}

/** Layers that reach the painter, in order, with invisible branches removed. */
export function visibleLayersInPaintOrder(layers: readonly Layer[]): Layer[] {
  return resolveLayerOrder(layers).filter((layer) => !isLayerEffectivelyHidden(layers, layer));
}

/** All descendants of a layer, depth-first in paint order. */
export function descendantsOf(layers: readonly Layer[], id: string): Layer[] {
  const result: Layer[] = [];
  const walk = (parentId: string) => {
    for (const child of childrenOf(layers, parentId).sort(compareLayerOrder)) {
      result.push(child);
      walk(child.id);
    }
  };
  walk(id);
  return result;
}

export function collectTextLayers(layers: readonly Layer[]): TextLayer[] {
  return layers.filter(isTextLayer);
}

export function collectMediaLayers(layers: readonly Layer[]): MediaLayer[] {
  return layers.filter(isMediaLayer);
}

