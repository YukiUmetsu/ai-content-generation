/**
 * Renderer-neutral M0 media document.
 *
 * A `MediaDocument` is a single fixed-size artboard ("still"): explicit
 * dimensions, stable layer identity, typed typography, referenced assets and
 * non-exporting guides. It is plain JSON — no functions, no DOM nodes, no
 * implicit network access — so the same record can be serialized, round-tripped
 * and later interpreted by a canvas/scene-graph adapter without reusing DOM.
 *
 * This module owns geometry, identity, validation, deterministic serialization
 * and authoring-time retargeting. Text measurement lives in `./text-layout` and
 * rendering lives in `./svg-export`; keeping them separate lets each be tested
 * without a browser or a renderer.
 *
 * Design-space rules (from docs/07 and docs/11):
 * - Origin is top-left, +x right, +y down, all values in design pixels.
 * - Output scaling must not change layout decisions; retargeting happens at
 *   authoring time and never stretches one aspect into another.
 * - Ids are stable across save/reload and are never regenerated by rendering.
 */

