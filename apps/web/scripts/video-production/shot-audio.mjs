async function makeSound(name, dir) {
  const path = join(dir, `${name}.wav`);
  await access(path).catch(() => exec("ffmpeg", ["-hide_banner", "-loglevel", "error", "-nostdin", "-y", "-filter_complex", RECIPES[name],
    "-ar", String(AUDIO_SAMPLE_RATE), "-ac", "1", "-c:a", "pcm_s16le", path]));
  return path;
}

/** Synthesize once per text and voice. A retry never pays twice for the same line. */
export async function synthesizeLines(lines, { dir, locale, modelId, apiKey, signal }, { synthesize = synthesizeFishBeat } = {}) {
  await mkdir(dir, { recursive: true });
  const out = [];
  for (const line of lines) {
    const key = createHash("sha256").update(JSON.stringify([line.text, line.voiceId, modelId, locale, line.pace ?? "measured"])).digest("hex").slice(0, 32);
    const wavPath = join(dir, `${key}.wav`);
    if (await access(wavPath).then(() => false, () => true)) {
      const result = await synthesize({ text: line.text, locale, voiceId: line.voiceId, modelId, direction: { pace: line.pace ?? "measured" }, allowNetwork: true,
        rightsContext: { voiceReferenceConsent: true, textTransmissionApproved: true } }, { apiKey, signal });
      const raw = join(dir, `${key}.raw.wav`);
      await writeFile(raw, result.audio);
      await normalizeGeneratedWav(raw, `${wavPath}.tmp.wav`, { signal });
      await rename(`${wavPath}.tmp.wav`, wavPath);
      await rm(raw);
    }
    const { samples } = await probeNormalizedWav(wavPath, { signal });
    out.push({ ...line, wavPath, samples, sha256: createHash("sha256").update(await readFile(wavPath)).digest("hex") });
  }
  return out;
}

async function silentWav(path, samples) {
  await exec("ffmpeg", ["-hide_banner", "-loglevel", "error", "-nostdin", "-y", "-f", "lavfi", "-i", `anullsrc=r=${AUDIO_SAMPLE_RATE}:cl=mono`,
    "-af", `atrim=end_sample=${samples}`, "-c:a", "pcm_s16le", path]);
}

