export async function masterShotAudio({ lines, layout, contacts, materials, accentFrame, fps, dir, output }) {
  await mkdir(dir, { recursive: true });
  const timeline = structuredClone(layout.timeline);
  const byId = new Map(lines.map(line => [line.id, line]));
  const beats = [];
  for (const beat of timeline.beats) {
    if (beat.silent) {
      const wavPath = join(dir, `${beat.id}.wav`);
      await silentWav(wavPath, beat.samples);
      beats.push({ id: beat.id, wavPath, samples: beat.samples, text: "", intentionalSilence: true,
        sha256: createHash("sha256").update(await readFile(wavPath)).digest("hex") });
    } else {
      const line = byId.get(beat.id);
      beats.push({ id: line.id, wavPath: line.wavPath, samples: line.samples, sha256: line.sha256, text: line.text });
    }
  }
  const sfx = [{ id: "room-tone", kind: "ambience", eventId: "start", assetPath: await makeSound("room-tone", dir), licenseStatus: "verified", gainDb: -30, fadeOutMs: 800 }];
  timeline.eventSamples.start = 0;
  for (const event of foleyEvents(contacts, materials, fps)) {
    timeline.eventSamples[event.id] = event.sample;
    sfx.push({ id: event.id, eventId: event.id, assetPath: await makeSound(event.sound, dir), licenseStatus: "verified", gainDb: event.sound === "paper-land" ? -9 : -16 });
  }
  if (accentFrame !== undefined) {
    timeline.eventSamples.accent = frameToSample(accentFrame, fps);
    sfx.push({ id: "accent", eventId: "accent", assetPath: await makeSound("reveal-accent", dir), licenseStatus: "verified", gainDb: -18 });
  }
  return renderMasterAudio({ beats, timeline, sfx }, { outputDir: output });
}
