const exec = promisify(execFile);

export function frameToSample(frame, fps) {
  const numerator = BigInt(frame) * BigInt(AUDIO_SAMPLE_RATE) * BigInt(fps.den);
  return Number((2n * numerator + BigInt(fps.num)) / (2n * BigInt(fps.num)));
}

/** Measured lines placed on the shot. Each line starts at its earliest frame, or after the previous line. */
export function layoutLines(lines, { fps, durationFrames, minGapFrames = 6 }) {
  const totalSamples = frameToSample(durationFrames, fps);
  const beats = [], windows = {};
  let cursor = 0, previousEnd = 0;
  const silence = (id, samples) => {
    if (samples <= 0) return;
    beats.push({ id, startSample: cursor, endSample: cursor + samples, pauseEndSample: cursor + samples, silent: true, samples });
    cursor += samples;
  };
  for (const line of lines) {
    const earliest = Math.max(line.notBeforeFrame ?? 0, previousEnd + (beats.length ? minGapFrames : 0));
    silence(`${line.id}-lead`, frameToSample(earliest, fps) - cursor);
    const startFrame = toFrame(cursor, fps), endSample = cursor + line.samples;
    if (endSample > totalSamples) throw Error(`Line ${line.id} overruns the ${durationFrames}-frame shot.`);
    const endFrame = toFrame(endSample, fps);
    beats.push({ id: line.id, startSample: cursor, endSample, pauseEndSample: endSample, samples: line.samples });
    windows[line.id] = { startFrame, endFrame };
    cursor = endSample;
    previousEnd = endFrame;
  }
  silence("tail", totalSamples - cursor);
  for (const beat of beats) Object.assign(beat, { startFrame: toFrame(beat.startSample, fps), endFrame: toFrame(beat.endSample, fps), pauseEndFrame: toFrame(beat.pauseEndSample, fps) });
  return { windows, timeline: { sampleRate: AUDIO_SAMPLE_RATE, fps, beats, eventSamples: {}, eventFrames: {},
    totalSamples, totalFrames: toFrame(totalSamples, fps) } };
}

const CONTACT_SOUND = Object.freeze({ paper: { place: "paper-land", grasp: "paper-lift" } });

/** Sounds for real contacts. An object with no declared material stays silent. */
export function foleyEvents(contacts, materials, fps) {
  // Objects that start in a hand "grasp" on frame 1. Nothing touched anything, so nothing sounds.
  return contacts.filter(contact => contact.frame > 1).flatMap(contact => {
    const sound = CONTACT_SOUND[materials[contact.object]]?.[contact.kind];
    return sound ? [{ id: `${contact.kind}-${contact.object}-${contact.frame}`, sound, sample: frameToSample(contact.frame, fps) }] : [];
  });
}

