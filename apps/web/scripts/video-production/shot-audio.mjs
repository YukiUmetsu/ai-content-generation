/** Voices, foley and mastering for one shot. Measured speech sets the clock.
 * Synthesis and mixing reuse fish.mjs and audio.mjs. This file only lays out the shot.
 */
import { createHash } from "node:crypto";
import { execFile } from "node:child_process";
