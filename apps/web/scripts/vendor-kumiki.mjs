#!/usr/bin/env node
/**
 * Vendors pinned Kumiki-UI source into this app.
 *
 * Kumiki ships one root `registry.json` manifest (not per-item JSON files), so the
 * shadcn CLI cannot fetch individual items from the pinned commit. This script is
 * the reproducible replacement: it resolves the manifest's dependency closure,
 * copies each file byte-for-byte, and records SHA-256 hashes in
 * `vendor/kumiki.lock.json`.
 *
 *   node scripts/vendor-kumiki.mjs                 # verify vendored files against the lock
 *   node scripts/vendor-kumiki.mjs --update-lock   # vendor from the pinned commit and rewrite the lock
 *   node scripts/vendor-kumiki.mjs --from ../kumiki-ui   # vendor from a local checkout
 *
 * No file is written outside this app directory beyond the OS temp cache.
 */
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, posix, relative, resolve } from "node:path";
import { dedupeVendorFiles, targetForRegistryFile } from "./vendor-kumiki-paths.mjs";
import { fileURLToPath } from "node:url";

const APP_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CONFIG_PATH = join(APP_ROOT, "kumiki.config.json");
const LOCK_PATH = join(APP_ROOT, "vendor", "kumiki.lock.json");

const args = process.argv.slice(2);
const fromIndex = args.indexOf("--from");
const localSource = fromIndex === -1 ? null : resolve(process.cwd(), args[fromIndex + 1]);
const updateLock = args.includes("--update-lock");

const config = JSON.parse(await readFile(CONFIG_PATH, "utf8"));
const rawBase = config.repository.replace("https://github.com/", "https://raw.githubusercontent.com/");

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

async function readSource(path) {
  if (localSource) {
    return readFile(join(localSource, path));
  }
  const url = `${rawBase}/${config.commit}/${path}`;
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`GET ${url} failed with ${response.status}. Check the pinned commit and path.`);
  }
  return Buffer.from(await response.arrayBuffer());
}

const manifest = JSON.parse((await readSource(config.manifest)).toString("utf8"));
const byName = new Map(manifest.items.map((item) => [item.name, item]));

const resolved = [];
const queue = [...config.items];
const seen = new Set();
while (queue.length > 0) {
  const name = queue.shift();
  if (seen.has(name)) continue;
  seen.add(name);
  const item = byName.get(name);
  if (!item) throw new Error(`Registry item "${name}" is not present in ${config.manifest}.`);
  resolved.push(item);
  for (const dependency of item.registryDependencies ?? []) queue.push(dependency);
}

const files = [];
const npmDependencies = {};

for (const item of resolved) {
  for (const dependency of item.dependencies ?? []) {
    npmDependencies[dependency] = npmDependencies[dependency] ?? item.name;
  }
  for (const file of item.files ?? []) {
    files.push({
      item: item.name,
      source: file.path,
      target: targetForRegistryFile(file.path, config.componentRoot ?? "src/components"),
    });
  }
}

for (const style of config.styles) {
  files.push({ item: "styles", source: style, target: join("src/styles/kumiki", style.split("/").pop()) });
}

const lock = {
  $comment: "Generated by scripts/vendor-kumiki.mjs. Do not edit by hand.",
  repository: config.repository,
  commit: config.commit,
  items: resolved.map((item) => item.name),
  npmDependencies,
  files: [],
};

const uniqueFiles = dedupeVendorFiles(files);

for (const file of uniqueFiles) {
  const bytes = await readSource(file.source);
  const digest = sha256(bytes);
  const absolute = join(APP_ROOT, file.target);

  if (updateLock) {
    await mkdir(dirname(absolute), { recursive: true });
    // Write only when content changed so repeat runs keep the diff empty.
    let current = null;
    try {
      current = await readFile(absolute);
    } catch {
      current = null;
    }
    if (!current || sha256(current) !== digest) {
      await writeFile(absolute, bytes);
      console.log(`updated  ${file.target}`);
    } else {
      console.log(`unchanged ${file.target}`);
    }
    lock.files.push({ item: file.item, source: file.source, target: file.target, sha256: digest, bytes: bytes.length });
    continue;
  }

  let existing;
  try {
    existing = await readFile(absolute);
  } catch {
    throw new Error(`Missing vendored file ${file.target}. Run with --update-lock.`);
  }
  if (sha256(existing) !== digest) {
    throw new Error(
      `Vendored file ${file.target} drifted from ${config.commit}. Restore it or bump the pin with --update-lock after review.`,
    );
  }
  lock.files.push({ item: file.item, source: file.source, target: file.target, sha256: digest, bytes: bytes.length });
  console.log(`verified ${file.target}`);
}

if (updateLock) {
  await mkdir(dirname(LOCK_PATH), { recursive: true });
  await writeFile(LOCK_PATH, `${JSON.stringify(lock, null, 2)}\n`);
  console.log(`\nWrote ${relative(APP_ROOT, LOCK_PATH)} (${lock.files.length} files, commit ${config.commit.slice(0, 12)}).`);
} else {
  const committed = JSON.parse(await readFile(LOCK_PATH, "utf8"));
  if (committed.commit !== config.commit) {
    throw new Error(`kumiki.config.json pins ${config.commit} but the lock records ${committed.commit}.`);
  }
  if (JSON.stringify(committed.items) !== JSON.stringify(lock.items)) {
    throw new Error("Kumiki item closure differs from the lock. Run with --update-lock after review.");
  }
  if (JSON.stringify(committed.npmDependencies) !== JSON.stringify(lock.npmDependencies)) {
    throw new Error("Kumiki npm dependency closure differs from the lock. Run with --update-lock after review.");
  }
  console.log(`\nAll ${lock.files.length} vendored files match commit ${config.commit.slice(0, 12)}.`);
}
